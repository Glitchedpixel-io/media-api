class TitleContentRepository(Protocol):
    def can_reach(
        self, start_title_id: int, target_title_id: int, max_depth: int = ...
    ) -> bool: ...
    def counts_for_titles(self, title_ids: Sequence[int]) -> dict[int, TitleContentCounts]: ...
    def totals_for_titles(
        self, title_ids: Sequence[int], max_depth: int = ...
    ) -> dict[int, TitleMediaTotals]: ...
    def create(self, title_content: TitleContentCreateInternal) -> TitleContentRead: ...
    def get(self, title_content_id: int) -> TitleContentRead | None: ...
    def exists(self, title_content_id: int) -> bool: ...
    def list_title_content(
        self, parent_title_id: int, include_children: bool = False
    ) -> list[TitleContentReadExtended]: ...
    def update(
        self,
        title_content_id: int,
        update: TitleContentUpdateInternal,  # type: ignore
    ) -> TitleContentRead: ...
    def delete_title_content(self, title_content_id: int) -> None: ...
    def get_titles_with_asset(self, asset_id: int) -> list[TitleContentReadParent]: ...
    def get_parents_of_title(self, title_id: int) -> list[TitleContentReadParent]: ...
    def intrinsic_parent_edge_id(self, child_title_id: int) -> int | None: ...

    # Ordering. `anchor` is "start" or "end"; it is named that rather than `position`
    # so it cannot be read as the integer column of the same name.
    def reorder(
        self,
        parent_title_id: int,
        title_content_id: int,
        *,
        before_id: int | None = None,
        after_id: int | None = None,
        anchor: str | None = None,
    ) -> TitleContentRead | None: ...

    def create_positioned(
        self,
        parent_title_id: int,
        title_content: TitleContentInsert,
        *,
        before_id: int | None = None,
        after_id: int | None = None,
        anchor: str | None = None,
    ) -> TitleContentRead | None: ...

    # Batch writes (#179). Each applies as one transaction under one set of parent
    # locks; the service validates every item before calling them, so these do not
    # re-check what a single write's service path checks.
    def create_many_positioned(
        self, parent_title_id: int, inserts: Sequence[TitleContentInsert]
    ) -> list[TitleContentRead]: ...

    def delete_many(self, parent_title_id: int, title_content_ids: Sequence[int]) -> int: ...

    def move_many(
        self, destination_title_id: int, title_content_ids: Sequence[int]
    ) -> list[TitleContentRead]: ...


