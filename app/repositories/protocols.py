    def create(self, ref: ExternalIdentifierCreateInternal) -> ExternalIdentifierRead: ...
    def update(
        self, record_id: int, update: ExternalIdentifierUpdateInternal
    ) -> ExternalIdentifierRead: ...
    def delete(self, record_id: int) -> None: ...


